export function ProductModule({ name, title, data, role, open, initialTab }) {
  const options = groups[name];
  const tabs = [...Object.keys(options), ...(name === 'content' ? ['Уведомления'] : [])];
  const [tab, set] = useState(initialTab || tabs[0]);
  const [selected, setSelected] = useState(null);
  const [preview, setPreview] = useState(false);
  const noticeItems = data.tickets.filter(t => (role === 'admin' ? t.company === actors.admin.company : t.owner === role) && t.firstReply)
    .map(t => ({ id: t.id, title: `Ответ УК на обращение №${t.id}`, text: t.title, action: () => open('ticket', t.id) }));
  return <section className="surface work-section">
    <h2>{title}</h2>
    {tabs.length > 1 && <Tabs values={tabs} value={tab} onChange={set} />}
    {tab === 'Уведомления' ? <div className="module-list">
      <button onClick={() => setSelected(vent)}><span><b>{vent.title}</b><small>Новости здания · 24 ноября</small></span><Icon name="right" /></button>
      {noticeItems.map(item => <button key={item.id} onClick={item.action}><span><b>{item.title}</b><small>{item.text}</small></span><Icon name="right" /></button>)}
    </div> : <div className="module-list">{options[tab].map(item =>
      <button key={item.title} onClick={() => { setSelected(item); setPreview(false); }}><span><b>{item.title}</b><small>{item.description}</small></span><Icon name="right" /></button>
    )}</div>}
    {name === 'publications' && <Outside items={['Редактировать публикацию', 'Рассылка', 'Опрос', 'Подтверждение прочтения']} />}
    {selected && <Modal title={selected.title} eyebrow={title} onClose={() => setSelected(null)}>
      <div className="flow"><p>{selected.description}</p>
        {!preview && <DetailList items={selected.facts} />}
        {name === 'publications' && <Button variant="outline" onClick={() => setPreview(!preview)}>
          {preview ? 'Показать настройки публикации' : 'Предпросмотр для арендатора'}</Button>}
        {selected === assetMove && <Button variant="outline" onClick={() => { setSelected(null); open('visit', 211); }}>Открыть связанный пропуск Г-211</Button>}
        {selected.actions.length > 0 && <Outside items={selected.actions} />}
        <Button variant="text" icon="left" onClick={() => setSelected(null)}>Назад к списку</Button>
      </div>
    </Modal>}
  </section>;
}
